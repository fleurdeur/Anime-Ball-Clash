enum class CharacterClass(val displayName: String, val shortRole: String) {
    ATTACKER("Bruiser", "Heavy Impact"),
    SPEEDSTER("Blitz", "High Velocity"),
    CONTROL_MAGIC("Tactician", "Control & Hex")
